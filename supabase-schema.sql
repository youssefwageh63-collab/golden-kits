-- أنشئ جدول الطلبات في مشروع Supabase ثم نفّذ هذا الملف في SQL Editor.
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  phone text not null,
  area text not null,
  address text not null,
  notes text,
  items jsonb not null,
  total numeric not null,
  payment_method text not null default 'الدفع عند الاستلام',
  status text not null default 'جديد',
  created_at timestamptz not null default now()
);
alter table public.orders enable row level security;
-- يسمح للزائر بإرسال طلب جديد فقط. لا تفتح قراءة الطلبات للعامة.
create policy "public can submit orders" on public.orders
for insert to anon with check (true);
